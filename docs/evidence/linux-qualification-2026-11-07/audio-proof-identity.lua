local f=assert(io.open('/tmp/spectr-audio-proof.txt','w'))
for i,name in ipairs({'VST3: Spectr','CLAP: Spectr'}) do
 reaper.InsertTrackAtIndex(i-1,false)
 local tr=reaper.GetTrack(0,i-1)
 reaper.SetOnlyTrackSelected(tr)
 reaper.SetEditCurPos(0,false,false)
 reaper.InsertMedia('/tmp/spectr-tone.wav',0)
 reaper.SetMediaTrackInfo_Value(tr,'D_PAN',i==1 and -1 or 1)
 local ix=reaper.TrackFX_AddByName(tr,name,false,-1)
 f:write(name,' index=',ix,'\n');f:flush()
 if ix<0 then error('Missing '..name) end
 reaper.TrackFX_SetParamNormalized(tr,ix,0,0)
 reaper.TrackFX_SetParamNormalized(tr,ix,3,0)
 local env=reaper.GetFXEnvelope(tr,ix,1,true)
 assert(env,'no output envelope')
 local _,lo,hi=reaper.TrackFX_GetParam(tr,ix,1)
 f:write('output_range=',lo,',',hi,'\n')
 reaper.InsertEnvelopePoint(env,0,lo+(hi-lo)*0.25,1,0,false,true)
 reaper.InsertEnvelopePoint(env,2,lo+(hi-lo)*0.75,1,0,false,true)
 reaper.InsertEnvelopePoint(env,4,lo+(hi-lo)*0.75,1,0,false,true)
 reaper.Envelope_SortPoints(env)
 reaper.SetMediaTrackInfo_Value(tr,'I_AUTOMODE',1)
 f:write('envelope_points=',reaper.CountEnvelopePoints(env),'\n')
end
reaper.GetSetProjectInfo(0,'RENDER_BOUNDSFLAG',0,true)
reaper.GetSetProjectInfo(0,'RENDER_STARTPOS',0,true)
reaper.GetSetProjectInfo(0,'RENDER_ENDPOS',4,true)
reaper.GetSetProjectInfo(0,'RENDER_SRATE',48000,true)
reaper.GetSetProjectInfo(0,'RENDER_CHANNELS',2,true)
reaper.GetSetProjectInfo(0,'RENDER_SETTINGS',0,true)
reaper.GetSetProjectInfo(0,'RENDER_TAILFLAG',0,true)
reaper.GetSetProjectInfo_String(0,'RENDER_FILE','/tmp',true)
reaper.GetSetProjectInfo_String(0,'RENDER_PATTERN','spectr-audio-proof-identity',true)
reaper.GetSetProjectInfo_String(0,'RENDER_FORMAT','ZXZhdxgAAA==',true)
reaper.Main_SaveProjectEx(0,'/tmp/spectr-audio-proof.RPP',0)
f:write('project_saved\n'); f:close()
reaper.Main_OnCommand(41824,0)
